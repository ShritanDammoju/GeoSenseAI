// Helper to compute 7-day moving average
function with7dMA(data: { date: string; count: number; satellite: 'VIIRS (375m)' | 'MODIS (1km)'; confidenceLevel: 'High' | 'Nominal' | 'Low'; cloudCoverEstimatePct: number }[]) {
  return data.map((item, idx, arr) => {
    const windowStart = Math.max(0, idx - 6);
    const windowSlice = arr.slice(windowStart, idx + 1);
    const sum = windowSlice.reduce((acc, curr) => acc + curr.count, 0);
    const avg = Math.round(sum / windowSlice.length);
    return {
      ...item,
      movingAverage7d: avg,
    };
  });
}

